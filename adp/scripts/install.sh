#!/usr/bin/env bash
set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; DIM='\033[2m'; RESET='\033[0m'

clear
echo -e "${CYAN}${BOLD}"
cat << 'EOF'
    ___    ____  ____
   /   |  / __ \/ __ \
  / /| | / / / / /_/ /
 / ___ |/ /_/ / ____/
/_/  |_/_____/_/
EOF
echo -e "${RESET}${BOLD}  Admin Deployment Panel  v1.0.0${RESET}"
echo -e "${DIM}  VPS Server Management — Full Featured${RESET}"
echo -e "\n${DIM}  ──────────────────────────────────────${RESET}\n"

ADP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# ── dependency check ─────────────────────────────────────────
echo -e "${BOLD}[1/5] Checking dependencies...${RESET}"

fail() { echo -e "  ${RED}✗ $1${RESET}"; exit 1; }
ok()   { echo -e "  ${GREEN}✓${RESET} $1"; }

command -v node &>/dev/null || fail "Node.js not found — install Node 18+ first"
node -e "if(parseInt(process.version.slice(1))<18)process.exit(1)" || fail "Node.js 18+ required (current: $(node -v))"
ok "Node.js $(node -v)"

command -v npm &>/dev/null || fail "npm not found"
ok "npm $(npm -v)"

if ! command -v pm2 &>/dev/null; then
  echo -e "  ${YELLOW}→ Installing pm2 globally...${RESET}"
  npm install -g pm2 --silent
fi
ok "pm2 $(pm2 -v)"

# ── helpers ──────────────────────────────────────────────────
ask() {
  local prompt="$1" default="$2" val
  printf "  ${BOLD}%-35s${RESET}${DIM}[%s]${RESET}: " "$prompt" "$default"
  read -r val
  echo "${val:-$default}"
}

ask_secret() {
  local prompt="$1" val
  printf "  ${BOLD}%-35s${RESET}: " "$prompt"
  read -rs val; echo
  echo "$val"
}

ask_choice() {
  local prompt="$1" opt1="$2" opt2="$3" default="$4" val
  printf "  ${BOLD}%-35s${RESET}${DIM}[%s/%s]${RESET}: " "$prompt" "$opt1" "$opt2"
  read -r val
  val="${val:-$default}"
  [[ "$val" == "$opt1" || "$val" == "$opt2" ]] || val="$default"
  echo "$val"
}

# ── server config ─────────────────────────────────────────────
echo -e "\n${BOLD}[2/5] Server configuration${RESET}"
PORT=$(ask "Port" "3000")
CORS_ORIGIN=$(ask "Your domain / CORS origin" "http://localhost:$PORT")
PROJECT_ROOT=$(ask "Projects root directory" "/opt/adp/projects")

# ── database ──────────────────────────────────────────────────
echo -e "\n${BOLD}[3/5] Database${RESET}"
DB_ENGINE=$(ask_choice "Database engine" "postgresql" "mariadb" "postgresql")

if [[ "$DB_ENGINE" == "postgresql" || "$DB_ENGINE" == "postgres" ]]; then
  DB_HOST=$(ask "PostgreSQL host" "localhost")
  DB_PORT=$(ask "PostgreSQL port" "5432")
  DB_NAME=$(ask "PostgreSQL database" "adp")
  DB_USER=$(ask "PostgreSQL user" "adp")
  DB_PASS=$(ask_secret "PostgreSQL password")
else
  DB_HOST=$(ask "MariaDB host" "localhost")
  DB_PORT=$(ask "MariaDB port" "3306")
  DB_NAME=$(ask "MariaDB database" "adp")
  DB_USER=$(ask "MariaDB user" "adp")
  DB_PASS=$(ask_secret "MariaDB password")
fi

# ── admin account ─────────────────────────────────────────────
echo -e "\n${BOLD}[4/5] Admin account${RESET}"
ADMIN_USER=$(ask  "Admin username"  "admin")
ADMIN_EMAIL=$(ask "Admin email"     "admin@localhost")

while true; do
  ADMIN_PASS=$(ask_secret "Admin password (min 8 chars)")
  ADMIN_PASS2=$(ask_secret "Confirm password")
  [[ "$ADMIN_PASS" == "$ADMIN_PASS2" && ${#ADMIN_PASS} -ge 8 ]] && break
  echo -e "  ${RED}✗ Passwords don't match or too short, try again${RESET}"
done

# ── generate secrets & write .env ────────────────────────────
JWT_SECRET=$(node -e "console.log(require('crypto').randomBytes(48).toString('hex'))")
COOKIE_SECRET=$(node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")

ENV_FILE="$ADP_DIR/.env"
cat > "$ENV_FILE" <<EOF
# ADP — generated by install.sh
PORT=$PORT
NODE_ENV=production
JWT_SECRET=$JWT_SECRET
COOKIE_SECRET=$COOKIE_SECRET
SESSION_TTL_HOURS=24
DB_ENGINE=$DB_ENGINE
DB_HOST=$DB_HOST
DB_PORT=$DB_PORT
DB_NAME=$DB_NAME
DB_USER=$DB_USER
DB_PASSWORD=$DB_PASS
EOF

if [[ "$DB_ENGINE" == "postgresql" || "$DB_ENGINE" == "postgres" ]]; then
cat >> "$ENV_FILE" <<EOF
POSTGRES_HOST=$DB_HOST
POSTGRES_PORT=$DB_PORT
POSTGRES_DB=$DB_NAME
POSTGRES_USER=$DB_USER
POSTGRES_PASSWORD=$DB_PASS
EOF
else
cat >> "$ENV_FILE" <<EOF
MARIADB_HOST=$DB_HOST
MARIADB_PORT=$DB_PORT
MARIADB_DB=$DB_NAME
MARIADB_USER=$DB_USER
MARIADB_PASSWORD=$DB_PASS
EOF
fi

cat >> "$ENV_FILE" <<EOF
PROJECT_ROOT=$PROJECT_ROOT
CORS_ORIGIN=$CORS_ORIGIN
ADMIN_USERNAME=$ADMIN_USER
ADMIN_EMAIL=$ADMIN_EMAIL
ADMIN_PASSWORD=$ADMIN_PASS
EOF

chmod 600 "$ENV_FILE"

mkdir -p "$PROJECT_ROOT" "$ADP_DIR/logs"
echo -e "  ${GREEN}✓${RESET} .env written & directories created"

# ── build ─────────────────────────────────────────────────────
echo -e "\n${BOLD}[5/5] Installing & building...${RESET}"

echo -e "  ${DIM}→ Installing backend deps...${RESET}"
(cd "$ADP_DIR/backend" && npm install --silent)

echo -e "  ${DIM}→ Installing frontend deps...${RESET}"
(cd "$ADP_DIR/frontend" && npm install --silent)

echo -e "  ${DIM}→ Building backend...${RESET}"
(cd "$ADP_DIR/backend" && npm run build)

echo -e "  ${DIM}→ Building frontend...${RESET}"
(cd "$ADP_DIR/frontend" && NODE_OPTIONS="${NODE_OPTIONS:---max-old-space-size=640}" npm run build)

echo -e "  ${GREEN}✓${RESET} Build complete"

# ── start pm2 ─────────────────────────────────────────────────
pm2 delete adp 2>/dev/null || true
pm2 start "$ADP_DIR/ecosystem.config.js" --env production
pm2 save

# ── pm2 startup ───────────────────────────────────────────────
echo -e "\n  ${DIM}Configuring PM2 startup on reboot...${RESET}"
STARTUP_CMD=$(pm2 startup 2>/dev/null | grep "sudo" | head -1 || true)
if [[ -n "$STARTUP_CMD" ]]; then
  eval "$STARTUP_CMD" 2>/dev/null || echo -e "  ${YELLOW}→ Run manually: $STARTUP_CMD${RESET}"
fi
pm2 save

# ── done ──────────────────────────────────────────────────────
LOCAL_IP=$(hostname -I 2>/dev/null | awk '{print $1}' || echo "your-ip")

echo ""
echo -e "${GREEN}${BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
echo -e "${GREEN}${BOLD}  ☠  ADP installed successfully!${RESET}"
echo -e "${GREEN}${BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
echo ""
echo -e "  ${CYAN}Open:${RESET}  http://${LOCAL_IP}:${PORT}"
echo -e "  ${CYAN}User:${RESET}  ${ADMIN_USER}"
echo ""
echo -e "  ${DIM}pm2 logs adp      — view logs${RESET}"
echo -e "  ${DIM}pm2 restart adp   — restart${RESET}"
echo -e "  ${DIM}pm2 status        — status${RESET}"
echo ""
